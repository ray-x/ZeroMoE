#!/usr/bin/env python3
"""Generate a cpu_affinity_layers / pin_strategy TOML block from a MoEStream
usage histogram (the pin_file format: "layer expert count" per line).

Approach (config-only, no new engine code -- see pin_strategy="global_topn"
in core/engine_config.hpp):
  1. Rank layers by how many experts they need for TARGET_COVERAGE of their
     own traffic ("flatness"). The N flattest go to cpu_affinity_layers --
     pinning barely helps them anyway, so their miss cost is unavoidable
     and better accepted outright than chased with VRAM.
  2. Everything else stays VRAM-resident under pin_strategy="global_topn",
     with pinned_vram_capacity set to the requested slot budget and
     pin_global_floor_per_layer set so no remaining layer goes unprotected.

Usage:
  python3 tools/gen_pin_config.py <usage_file> [--cpu-layers N] \\
      [--budget SLOTS] [--coverage 0.95] [--floor-frac 0.5]
"""
import argparse
import sys
from collections import defaultdict


def load_histogram(path):
    layers = defaultdict(list)
    with open(path) as f:
        for line in f:
            parts = line.split()
            if len(parts) != 3:
                continue
            layer, _expert, count = int(parts[0]), int(parts[1]), int(parts[2])
            layers[layer].append(count)
    return layers


def coverage_count(counts, target):
    counts = sorted(counts, reverse=True)
    total = sum(counts)
    if total == 0:
        return len(counts)
    cum = 0
    for i, c in enumerate(counts, 1):
        cum += c
        if cum >= target * total:
            return i
    return len(counts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("usage_file")
    ap.add_argument("--cpu-layers", type=int, default=5,
                     help="how many flattest layers to send to cpu_affinity_layers")
    ap.add_argument("--budget", type=int, default=22 * 512,
                     help="total pinned_vram_capacity slot budget")
    ap.add_argument("--coverage", type=float, default=0.95,
                     help="traffic coverage target used to rank flatness")
    ap.add_argument("--floor-frac", type=float, default=0.5,
                     help="pin_global_floor_per_layer as a fraction of budget/n_vram_layers")
    args = ap.parse_args()

    layers = load_histogram(args.usage_file)
    if not layers:
        print(f"error: no (layer,expert,count) rows read from {args.usage_file}", file=sys.stderr)
        sys.exit(1)

    need = {l: coverage_count(c, args.coverage) for l, c in layers.items()}
    ranked = sorted(need.items(), key=lambda kv: kv[1], reverse=True)
    cpu_layers = sorted(l for l, _ in ranked[:args.cpu_layers])
    n_vram_layers = len(layers) - len(cpu_layers)
    floor = max(1, int(args.budget / max(1, n_vram_layers) * args.floor_frac))

    print(f"# Generated by tools/gen_pin_config.py from {args.usage_file}")
    print(f"# {len(layers)} layers total, {len(cpu_layers)} sent to CPU (flattest by "
          f"{int(args.coverage*100)}% coverage), {n_vram_layers} stay VRAM-resident "
          f"under global_topn.")
    print(f"cpu_affinity_layers = {cpu_layers}")
    print()
    print('pin_strategy = "global_topn"')
    print(f"pinned_vram_capacity = {args.budget}")
    print(f"pin_global_floor_per_layer = {floor}")
    print()
    print("# Flattest layers (excluded, sent to CPU) and their would-be coverage cost:",
          file=sys.stderr)
    for l, v in ranked[:args.cpu_layers]:
        print(f"#   layer {l:2d}: needed {v:3d}/{len(layers[l])} experts for "
              f"{int(args.coverage*100)}% coverage", file=sys.stderr)


if __name__ == "__main__":
    main()
